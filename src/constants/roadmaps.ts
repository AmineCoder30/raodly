export type NodeState = "completed" | "active" | "locked";

export type ModuleTopic = {
  id: string;
  title: string;
  completed?: boolean;
};

export type ModuleNode = {
  id: number;
  title: string;
  subtitle: string;
  state: NodeState;
  progress: number;
  topics: ModuleTopic[];
};

export type Roadmap = {
  id: string;
  level: "Beginner" | "Intermediate" | "Advanced";
  hours: number;
  title: string;
  description: string;
  topicsCompleted: number;
  topicsTotal: number;
  nextSectionTitle: string;
  isCompleted?: boolean;
  modulesCount: number;
  nodes: ModuleNode[];
};

function createTopics(
  prefix: string,
  titles: string[],
  completedCount = 0,
): ModuleTopic[] {
  return titles.map((title, index) => ({
    id: `${prefix}-${index + 1}`,
    title,
    completed: index < completedCount,
  }));
}

